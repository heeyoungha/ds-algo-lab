text = """
=========================================
정렬 + zip() + startswith()를 활용한 접두어 확인

전화번호 목록을 정렬한 후, 연속된 두 번호를 비교하여 접두어 관계를 확인하는 방법

🔹 sort()
- 리스트를 오름차순으로 정렬한다 (원본 수정).
- 문자열 정렬은 사전식 순서로 정렬된다.
- 정렬 후에는 접두어 관계가 있는 번호들이 인접하게 배치된다.

🔹 zip(phone_book, phone_book[1:])
- phone_book과 phone_book[1:]을 묶어서 연속된 두 요소를 비교한다.
- 예: ["119", "97674223", "1195524421"] 
  -> zip 결과: ("119", "97674223"), ("97674223", "1195524421")
- phone_book[1:]은 두 번째 요소부터 마지막까지의 리스트이다.

🔹 startswith()
- 문자열이 특정 접두어로 시작하는지 확인한다.
- b.startswith(a)는 b가 a로 시작하는지 확인한다.
- 정렬된 상태에서 a가 b의 접두어인지만 확인하면 된다.
  (정렬 후에는 a < b이므로 a가 b의 접두어일 수 있지만, b가 a의 접두어일 수는 없음)

🔹 시간복잡도
- sort(): O(n log n)  
  n은 phone_book의 길이
- zip() 순회: O(n) 
  n은 phone_book의 길이
- startswith(): O(m)
  m은 문자열의 길이 (최대 20)
- 전체 시간복잡도: O(n log n + n * m) ≈ O(n log n)
  (일반적으로 n이 크고 m이 작으므로)

🔹 공간복잡도: O(1) 
  정렬이 in-place로 수행되는 경우

✅ 장점:
- 정렬을 통해 접두어 관계를 효율적으로 확인 가능
- zip()을 사용하여 간결한 코드 작성
- 한 번의 정렬로 모든 접두어 관계 확인 가능

❌ 주의사항:
- 정렬 후에는 a < b인 경우만 확인하면 됨 (a가 b의 접두어인지만 확인)
- 정렬 전에는 양방향 확인이 필요하지만, 정렬 후에는 한 방향만 확인하면 됨
=========================================
"""
print(text)

phone_book = ["12","123","1235","567","88"]
phone_book.sort()
print(phone_book)
for a, b in zip(phone_book, phone_book[1:]):
    print(f"a: {a}, b: {b}")
    if b.startswith(a):
        print("True")
else:
    print("True")
